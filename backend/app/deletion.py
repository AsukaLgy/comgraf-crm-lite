"""Transactional, scope-checked deletion of CRM-owned records."""
from pathlib import Path
from fastapi import HTTPException
from sqlalchemy import delete, func, select, update
from sqlalchemy.sql.schema import Table
from .config import settings
from .db import SessionLocal
from .models import Base, Case, Client, Contact, Attachment, MailAttachment, MailMessage, Ledger, DeletionAudit, FileCleanup, now


def require_admin(user):
    if 'Administrador' not in (user.roles or []):
        raise HTTPException(403, 'Solo un Administrador puede eliminar definitivamente')


def _case_scope(db, case_ids):
    ids = sorted(set(case_ids))
    tables = {}
    for table in Base.metadata.sorted_tables:
        if table.name in {'deletion_audit', 'file_cleanup'}:
            continue
        if 'case_id' in table.c:
            tables[table.name] = table
    counts = {name: db.scalar(select(func.count()).select_from(table).where(table.c.case_id.in_(ids))) for name, table in tables.items()}
    messages = db.scalars(select(MailMessage.id).where(MailMessage.case_id.in_(ids))).all()
    counts['mail_attachments'] = db.scalar(select(func.count()).select_from(MailAttachment).where(MailAttachment.message_id.in_(messages))) if messages else 0
    return counts, tables, messages


def preview_cases(db, cases):
    counts, _, _ = _case_scope(db, [c.id for c in cases])
    return {'cases': [{'id': c.id, 'number': f'CG-{c.id:06d}', 'subject': c.subject, 'version': c.version} for c in cases],
            'counts': counts}


def preview_client(db, client):
    cases = db.scalars(select(Case).where(Case.client_id == client.id).order_by(Case.id)).all()
    return {'client': {'id': client.id, 'name': client.name, 'version': client.version},
            'contacts': db.scalar(select(func.count()).select_from(Contact).where(Contact.client_id == client.id)),
            **preview_cases(db, cases)}


def _delete_cases(db, cases, actor_id):
    if not cases:
        return
    ids = [c.id for c in cases]
    counts, tables, message_ids = _case_scope(db, ids)
    attachment_keys = db.scalars(select(Attachment.storage_key).where(Attachment.case_id.in_(ids))).all()
    if message_ids:
        attachment_keys += db.scalars(select(MailAttachment.storage_key).where(MailAttachment.message_id.in_(message_ids))).all()
        db.execute(delete(MailAttachment).where(MailAttachment.message_id.in_(message_ids)))
        db.execute(update(MailMessage).where(MailMessage.id.in_(message_ids)).values(retry_of_id=None))
    db.execute(update(Ledger).where(Ledger.case_id.in_(ids)).values(reverses_id=None))
    db.execute(update(Case).where(Case.related_case_id.in_(ids)).values(related_case_id=None))
    # SQLAlchemy's reversed FK ordering deletes dependents before parents.
    for table in reversed(Base.metadata.sorted_tables):
        if table.name in tables:
            db.execute(delete(table).where(table.c.case_id.in_(ids)))
    db.execute(delete(Case).where(Case.id.in_(ids)))
    for case in cases:
        db.add(DeletionAudit(actor_id=actor_id, record_type='case', record_id=case.id, deleted_at=now()))
    for key in attachment_keys:
        db.add(FileCleanup(storage_key=key, attempts=0))
    db.flush()


def delete_case(db, user, case_id, expected):
    require_admin(user)
    case = db.scalar(select(Case).where(Case.id == case_id).with_for_update())
    if not case:
        raise HTTPException(404, 'La solicitud ya no existe')
    actual = preview_cases(db, [case])
    if actual != expected:
        raise HTTPException(409, 'El alcance cambió. Revisa la confirmación actualizada.')
    _delete_cases(db, [case], user.id)


def delete_client(db, user, client_id, expected, include_cases):
    require_admin(user)
    client = db.scalar(select(Client).where(Client.id == client_id).with_for_update())
    if not client:
        raise HTTPException(404, 'El cliente ya no existe')
    actual = preview_client(db, client)
    if actual != expected:
        raise HTTPException(409, 'El alcance cambió. Revisa la confirmación actualizada.')
    cases = db.scalars(select(Case).where(Case.client_id == client_id).with_for_update()).all()
    if cases and not include_cases:
        raise HTTPException(409, 'Confirma expresamente eliminar el cliente y sus solicitudes')
    _delete_cases(db, cases, user.id)
    db.execute(delete(Contact).where(Contact.client_id == client_id))
    db.delete(client)
    db.add(DeletionAudit(actor_id=user.id, record_type='client', record_id=client_id, deleted_at=now()))
    db.flush()


def retry_file_cleanup():
    """Run only after the request transaction committed; failed jobs remain retryable."""
    with SessionLocal() as db:
        for job in db.scalars(select(FileCleanup).order_by(FileCleanup.id).limit(50)):
            try:
                # storage_key is generated by the CRM, never an external path.
                if '/' in job.storage_key or '\\' in job.storage_key or job.storage_key in {'.', '..'}:
                    raise ValueError('Invalid storage key')
                (Path(settings.upload_dir) / job.storage_key).unlink(missing_ok=True)
                db.delete(job)
            except (OSError, ValueError):
                job.attempts += 1
        db.commit()
