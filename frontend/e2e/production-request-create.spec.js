import { test, expect } from '@playwright/test'
import fs from 'node:fs'
import path from 'node:path'

const credentials = JSON.parse(fs.readFileSync(path.resolve('../.runtime/e2e.json'), 'utf8'))

test('Producción crea solicitud y OP juntas sin responsable', async ({ page }) => {
  const runtimeErrors = []
  const clientName = 'E2E · Alta atómica ' + Date.now()
  await page.goto('/')
  await page.getByLabel('Usuario', { exact: true }).fill(credentials.username)
  await page.getByLabel('Contraseña', { exact: true }).fill(credentials.password)
  await page.getByRole('button', { name: 'Iniciar sesión' }).click()
  await expect(page.getByRole('heading', { name: 'Mi día' })).toBeVisible()
  page.on('pageerror', (error) => runtimeErrors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error') runtimeErrors.push(message.text())
  })
  page.on('requestfailed', (request) => {
    if (/\.(js|css|png|ico)(\?|$)/i.test(request.url()))
      runtimeErrors.push(`Recurso faltante: ${request.url()}`)
  })
  await page.goto('/inbox/production')
  await page.getByRole('button', { name: 'Generar orden de producción' }).click()
  const dialog = page.getByRole('dialog')
  const clientInput = dialog.getByRole('combobox', { name: /Cliente/ })
  await clientInput.fill(clientName)
  await expect(dialog.getByRole('button', { name: /Crear cliente/ })).toBeVisible()
  await clientInput.press('Escape')
  await expect(dialog.getByRole('listbox')).toHaveCount(0)
  await expect(clientInput).toHaveValue(clientName)
  await clientInput.click()
  await dialog.getByRole('button', { name: /Crear cliente/ }).click()
  await dialog.getByLabel('Empresa / razón social').fill('Taller de prueba')
  await dialog.getByRole('button', { name: 'Crear y seleccionar cliente' }).click()
  await expect(dialog.getByRole('listbox')).toHaveCount(0)
  await expect(dialog.getByLabel('Contacto')).toHaveCount(0)
  await expect(dialog.getByText(/Se creará sin asignar en Bandeja general/)).toHaveCount(0)
  await expect(dialog.getByRole('radio', { name: 'Contado' })).toBeChecked()
  await expect(dialog.getByRole('radio', { name: 'Retiro en local' })).toBeChecked()
  await dialog.getByRole('radio', { name: 'Crédito' }).check()
  await expect(dialog.getByRole('radio', { name: 'Contado' })).not.toBeChecked()
  await dialog.getByRole('radio', { name: 'Contado' }).check()
  await dialog.getByRole('radio', { name: 'Entrega', exact: true }).check()
  await expect(dialog.getByRole('radio', { name: 'Retiro en local' })).not.toBeChecked()
  await dialog.getByRole('radio', { name: 'Retiro en local' }).check()
  await dialog.getByLabel('Asunto').fill('Alta atómica de prueba')
  await dialog.getByLabel('Cantidad').fill('100')
  await dialog.getByLabel('Precio unitario (HNL)').fill('15')
  await page.screenshot({ path: '../.runtime/production-create-desktop.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
  await page.screenshot({ path: '../.runtime/production-create-mobile.png', fullPage: true })
  await dialog.getByRole('button', { name: 'Crear solicitud y orden' }).click()
  await expect(dialog.getByText('Orden creada en Aprobación.')).toBeVisible()
  await dialog.getByRole('button', { name: 'Mantener en Aprobación' }).click()
  await expect(page).toHaveURL(/\/cases\/\d+\?tab=production&production_id=\d+/)
  const current = await (
    await page.request.get(new URL(page.url()).pathname.replace('/cases/', '/api/cases/'))
  ).json()
  expect(current.kind).toBe('Solicitud')
  expect(current.mode).toBe('Producción')
  expect(current.owner_id).toBeNull()
  expect(current.production.stage).toBe('APPROVAL')
  await expect(page.getByRole('heading', { name: 'Especificaciones de producción' })).toBeVisible()
  expect(runtimeErrors).toEqual([])
})
